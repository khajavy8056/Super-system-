def _fit(path: str, w: float, h_max: float) -> tuple[float, float]:
    """عرض/ارتفاع نهایی با حفظ نسبت — هیچ تصویری بلندتر از h_max نمی‌شود."""
    with Image.open(SHOTS / path) as im:
        iw, ih = im.size
    h = w * ih / iw
    if h > h_max:
        w = h_max * iw / ih
        h = h_max
    return w, h


def shot(path: str, caption: str = "", w: float | None = None):
    """یک اسکرین‌شات با کادر و زیرنویس — وسط صفحه؛ تصاویر عمودی کوچک‌شده تا کل صفحه را نگیرند."""
    if not (SHOTS / path).is_file():
        print(f"  !! تصویر یافت نشد: {path}")
        return
    with Image.open(SHOTS / path) as im:
        iw, ih = im.size
    w = w or EPW
    w, h = _fit(path, w, 175)  # mm — هیچ تصویری بلندتر از این نشود (صفحهٔ خالی/سرریز نسازد)
    if pdf.get_y() + h + (18 if caption else 12) > pdf.page_break_trigger:
        pdf.add_page()  # زیرنویس هم همراه تصویر بماند (یتیم نشود)
    x = M + (EPW - w) / 2
    pdf.image(str(SHOTS / path), x=x, w=w)
    pdf.set_draw_color(*LINE)
    pdf.set_line_width(0.25)
    pdf.rect(x, pdf.get_y() - h, w, h)
    if caption:
        pdf.ln(1.5)
        pdf.set_font("Vazir", "", 8.5)
        pdf.set_text_color(*MUTED)
        pdf.cell(EPW, 5, caption, align="C")
        pdf.ln(6)
    else:
        pdf.ln(4)


def shot_pair(p1: str, p2: str, caption: str = ""):
    """دو اسکرین‌شات موبایل، کنار هم."""
    if not ((SHOTS / p1).is_file() and (SHOTS / p2).is_file()):
        print(f"  !! جفت تصویر ناقص: {p1} / {p2}")
        return
    w1, h1 = _fit(p1, 58, 118)
    w2, h2 = _fit(p2, 58, 118)
    h = max(h1, h2)
    if pdf.get_y() + h + (18 if caption else 12) > pdf.page_break_trigger:
        pdf.add_page()
    y = pdf.get_y()
    gap = 12
    x1 = M + (EPW - w1 - w2 - gap) / 2
    pdf.image(str(SHOTS / p1), x=x1, y=y, w=w1)
    pdf.image(str(SHOTS / p2), x=x1 + w1 + gap, y=y, w=w2)
    pdf.set_draw_color(*LINE)
    pdf.set_line_width(0.25)
    pdf.rect(x1, y, w1, h1)
    pdf.rect(x1 + w1 + gap, y, w2, h2)
    pdf.set_y(y + h + 1.5)
    if caption:
        pdf.set_font("Vazir", "", 8.5)
        pdf.set_text_color(*MUTED)
        pdf.cell(EPW, 5, caption, align="C")
        pdf.ln(6)
    else:
        pdf.ln(4)


def section(num: str, title: str, lead: str = ""):
    """سرصفحهٔ بخش — با ثبت در فهرست."""
    pdf.start_section(f"{num}. {title}", 0)
    if pdf.get_y() > 235:
        pdf.add_page()
    else:
        pdf.ln(2)
    pdf.set_fill_color(*PRIMARY)
    pdf.set_draw_color(*PRIMARY)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Vazir", "B", 14)
    pdf.rect(M, pdf.get_y(), EPW, 11, round_corners=True, corner_radius=2.5, style="F")
    pdf.set_xy(M, pdf.get_y() + 1.4)
    pdf.cell(EPW - 5, 8, f"{num}. {title}", align="R")
    pdf.set_xy(M, pdf.get_y() - 1.4 + 11)
    pdf.set_text_color(*INK)
    if lead:
        p(lead)
    pdf.ln(0.5)


def h2(title: str):
    if pdf.get_y() > 262:
        pdf.add_page()
    pdf.ln(1.5)
    pdf.set_font("Vazir", "B", 11.5)
    pdf.set_text_color(*PRIMARY_D)
    pdf.cell(EPW, 7, title, align="R")
    pdf.set_draw_color(*ACCENT)
    pdf.set_line_width(0.6)
    y = pdf.get_y() + 6.4
    pdf.line(pdf.w - M - 26, y, pdf.w - M, y)
    pdf.set_line_width(0.2)
    pdf.ln(8.5)
    pdf.set_text_color(*INK)


def p(text: str, size: float = 10.3, style: str = "", color=INK):
    pdf.set_font("Vazir", style, size)
    pdf.set_text_color(*color)
    pdf.multi_cell(EPW, 6.1, text, align="R")
    pdf.ln(0.6)


def bullets(items: list[str], size: float = 10.1):
    """فهرست گلوله‌ای — تورفتگی از سمت راست."""
    pdf.set_font("Vazir", "", size)
    for it in items:
        if pdf.get_y() > 268:
            pdf.add_page()
        pdf.set_x(M)
        pdf.set_text_color(*PRIMARY)
        pdf.set_font("Vazir", "B", size)
        pdf.cell(4, 5.8, "•", align="R")
        pdf.set_x(M + 4)
        pdf.set_text_color(*INK)
        pdf.set_font("Vazir", "", size)
        pdf.multi_cell(EPW - 4, 5.8, it, align="R")
    pdf.ln(1.2)


def note(text: str):
    """کادر نکتهٔ طلایی."""
    if pdf.get_y() > 240:
        pdf.add_page()
    x, y = M, pdf.get_y()
    pdf.set_font("Vazir", "", 9.8)
    pdf.set_xy(M, y)
    pdf.multi_cell(EPW, 5.8, text, align="R")
    h = pdf.get_y() - y + 4
    pdf.set_fill_color(252, 246, 230)
    pdf.set_draw_color(*ACCENT)
    pdf.rect(M, y, EPW, h, round_corners=True, corner_radius=2, style="FD")
    pdf.set_xy(M + 3, y + 2)
    pdf.set_font("Vazir", "", 9.8)
    pdf.set_text_color(90, 70, 20)
    pdf.multi_cell(EPW - 6, 5.8, text, align="R")
    pdf.set_y(y + h + 2)
    pdf.set_text_color(*INK)


def render_toc(_pdf, outline):
    """فهرست مطالب — راست‌چین با شمارهٔ صفحه."""
    _pdf.set_font("Vazir", "B", 15)
    _pdf.set_text_color(*PRIMARY_D)
    _pdf.set_y(20)
    _pdf.cell(EPW, 10, "فهرست مطالب", align="R")
    _pdf.set_draw_color(*ACCENT)
    _pdf.set_line_width(0.8)
    _pdf.line(_pdf.w - M - 34, 30, _pdf.w - M, 30)
    _pdf.ln(13)
    for e in outline:
        if _pdf.get_y() > 275:
            break
        _pdf.set_font("Vazir", "B" if e.level == 0 else "", 10.5 if e.level == 0 else 9.8)
        _pdf.set_text_color(*INK if e.level == 0 else MUTED)
        title = e.name
        page = fa_num(e.page_number)
        _pdf.set_x(M)
        _pdf.cell(14, 7, page, align="L")
        _pdf.set_x(M + 14)
        _pdf.cell(EPW - 14, 7, title, align="R")
        y = _pdf.get_y() + 6.2
        _pdf.set_draw_color(*LINE)
        _pdf.set_line_width(0.15)
        _pdf.set_x(M)
        _pdf.cell(EPW, 0.8, "", align="C", border="B")
        _pdf.set_y(y)


