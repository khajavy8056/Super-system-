def fa_num(n) -> str:
    return str(n).translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))


class Guide(FPDF):
    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.set_margins(M, 14, M)
        self.set_auto_page_break(True, margin=16)
        self.add_font("Vazir", "", str(FONT_R))
        self.add_font("Vazir", "B", str(FONT_B))
        self.set_text_shaping(True)
        self._cover_done = False

    # ---------- header / footer ----------
    def header(self):
        if not self._cover_done:
            return
        self.set_font("Vazir", "", 8.5)
        self.set_text_color(*MUTED)
        self.set_y(7)
        self.cell(0, 5, "معرف‌نامهٔ کامل رسا سیستم (سوپری‌من)", align="R")
        self.cell(0, 5, f"v{VERSION}", align="L")
        self.set_draw_color(*LINE)
        self.set_line_width(0.2)
        self.line(M, 12, self.w - M, 12)
        self.set_y(16)

    def footer(self):
        if not self._cover_done:
            return
        self.set_y(-11)
        self.set_font("Vazir", "", 8.5)
        self.set_text_color(*MUTED)
        self.multi_cell(EPW, 6, f"صفحهٔ {fa_num(self.page_no())}", align="C")


